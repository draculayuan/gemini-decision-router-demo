def _png_chunk(chunk_type: bytes, data: bytes) -> bytes:
    crc = zlib.crc32(chunk_type + data) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + chunk_type + data + struct.pack(">I", crc)


def build_sample_receipt_png_b64() -> str:
    """Return a base64-encoded PNG receipt image for multimodal extraction demos."""
    width, height = 420, 320
    bg = (250, 249, 245)
    ink = (32, 33, 36)
    accent = (26, 115, 232)
    pixels = [[bg for _ in range(width)] for _ in range(height)]

    def draw_text(text: str, x0: int, y0: int, scale: int = 2, color: tuple[int, int, int] = ink) -> None:
        cursor_x = x0
        for ch in text.upper():
            glyph = _FONT_5X7.get(ch, _FONT_5X7[" "])
            for row_idx, row_bits in enumerate(glyph):
                for col_idx in range(5):
                    if (row_bits >> (4 - col_idx)) & 1:
                        for dy in range(scale):
                            for dx in range(scale):
                                px = cursor_x + col_idx * scale + dx
                                py = y0 + row_idx * scale + dy
                                if 0 <= px < width and 0 <= py < height:
                                    pixels[py][px] = color
            cursor_x += 6 * scale

    # Border
    for x in range(12, width - 12):
        pixels[12][x] = accent
        pixels[height - 13][x] = accent
    for y in range(12, height - 12):
        pixels[y][12] = accent
        pixels[y][width - 13] = accent

    lines = [
        ("BAY VIEW ROASTERS", 28, 30, 3, accent),
        ("ORDER #4082   2026-11-11", 28, 72, 2, ink),
        ("----------------------------", 28, 98, 2, ink),
        ("2X FLAT WHITE        $11.50", 28, 126, 2, ink),
        ("1X ALMOND CROISSANT   $5.25", 28, 154, 2, ink),
        ("1X MATCHA LATTE       $6.50", 28, 182, 2, ink),
        ("----------------------------", 28, 210, 2, ink),
        ("SUBTOTAL             $23.25", 28, 236, 2, ink),
        ("TAX 9.0%              $2.09", 28, 260, 2, ink),
        ("TOTAL PAID           $25.34", 28, 286, 2, accent),
    ]
    for text, x, y, sc, col in lines:
        draw_text(text, x, y, scale=sc, color=col)

    raw_rows = bytearray()
    for row in pixels:
        raw_rows.append(0)  # Filter type 0
        for r, g, b in row:
            raw_rows.extend((r, g, b))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    png_bytes = (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"IDAT", zlib.compress(bytes(raw_rows), level=6))
        + _png_chunk(b"IEND", b"")
    )
    return base64.b64encode(png_bytes).decode("ascii")
